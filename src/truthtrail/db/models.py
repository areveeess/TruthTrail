"""Declarative models of the Phase 3 schema (D-20): the schema's single source of truth.

The baseline Alembic revision (``migrations/versions/0001_baseline.py``) was autogenerated from
these models and then reviewed by hand; ``alembic check`` (and ``command.check`` in
``tests/test_migrations.py``) proves that the models and the migrations agree, so a change here
without a new revision fails CI.

Conventions:

- Every timestamp is ``timestamptz`` (``DateTime(timezone=True)``); the engine pins the session
  to UTC (RESEARCH F-15). Stream times from Jetstream are integer microseconds (``*_us``).
- Ids are ``bigint`` identity columns. Enumerations are ``varchar`` plus a named CHECK, never a
  database enum type, so a later value is a one-line constraint change.
- Constraint and index names come from one naming convention (``NAMING_CONVENTION``), so
  autogenerate, ``alembic check`` and ``downgrade`` are deterministic. The two partial indexes
  carry explicit names that say what they select.
- Every ``uri``-like column (``uri``, ``parent_uri``, ``reply_root_uri``, ``quoted_uri``,
  ``via_uri``, ``root_uri``) holds the 20-character keyed form of an ``at://`` URI and
  ``accounts.pseudonym`` the 16-character keyed form of a DID (D-17, scheme ``d17-hmac-v1``):
  no raw DID, handle, rkey or clear URI is ever stored. DATA-02's ``parent_uri`` is this column
  holding the keyed parent URI (D-15).

The database itself enforces the edge semantics (D-12), the orphan states (D-14), the tombstone
rule (D-16) and data minimisation (D-18) through the CHECK constraints below, so a writer bug
cannot store a root with a parent, text on a reply or a tombstone that still names its account.
Nothing synthetic is stored: no table has a ``synthetic`` column and no score, model or
simulation table exists in this phase (D-20).
"""

from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    Integer,
    MetaData,
    String,
    Text,
    func,
)
from sqlalchemy import text as sql_text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# RESEARCH Pattern 6: deterministic names for every constraint and index.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# Fixed key widths of the ratified pseudonymisation scheme d17-hmac-v1 (D-17).
URI_KEY_LENGTH = 20  # lowercase base32 of HMAC-SHA256("uri" NUL uri), 100 bits
PSEUDONYM_LENGTH = 16  # lowercase base32 of HMAC-SHA256("acct" NUL did), 80 bits
DIGEST_LENGTH = 26  # claim_key and text_hash: lowercase base32 of a truncated SHA-256

EDGE_KINDS = ("root", "reply", "quote", "repost")
PARENT_STATES = ("none", "resolved", "orphan", "invalid")
CLAIM_KINDS = ("social_link", "news_headline")
RUN_MODES = ("live", "replay")


def _in(column: str, values: tuple[str, ...]) -> str:
    """CHECK expression ``column IN ('a', 'b')`` over a fixed, module-level tuple."""
    quoted = ", ".join("'" + value + "'" for value in values)
    return column + " IN (" + quoted + ")"


def _now() -> Any:
    return func.now()


class Base(DeclarativeBase):
    """Declarative base whose metadata carries the naming convention."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class NewsQuery(Base):
    """A committed news topic (D-26): the job refreshes it; users never supply a query."""

    __tablename__ = "news_queries"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    slug: Mapped[str] = mapped_column(String(64), unique=True)
    query: Mapped[str] = mapped_column(String(200))
    last_attempt_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_success_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_status: Mapped[str | None] = mapped_column(String(24))


class Account(Base):
    """A pseudonymous account: only the keyed DID and when it was first seen (D-17, D-18)."""

    __tablename__ = "accounts"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    pseudonym: Mapped[str] = mapped_column(String(PSEUDONYM_LENGTH), unique=True)
    first_observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))


class Claim(Base):
    """A claim: a social root's linked article or a news headline (publisher text only).

    ``claim_key`` is the hash of the kind plus the canonical URL or text, unique, so writers
    upsert with a plain ``ON CONFLICT (claim_key)`` (RESEARCH Pattern 6).
    """

    __tablename__ = "claims"
    __table_args__ = (CheckConstraint(_in("kind", CLAIM_KINDS), name="kind"),)

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    kind: Mapped[str] = mapped_column(String(16))
    claim_key: Mapped[str] = mapped_column(String(DIGEST_LENGTH), unique=True)
    text: Mapped[str | None] = mapped_column(Text)
    text_hash: Mapped[str] = mapped_column(String(DIGEST_LENGTH))
    url_canonical: Mapped[str | None] = mapped_column(Text)
    link_domain: Mapped[str | None] = mapped_column(String(253))
    source_name: Mapped[str | None] = mapped_column(Text)
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    lang: Mapped[str | None] = mapped_column(String(8))
    query_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("news_queries.id", ondelete="SET NULL")
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=_now())


def _counter() -> Mapped[int]:
    return mapped_column(Integer, server_default=sql_text("0"))


class Cascade(Base):
    """One tracked root and its rollup counters (written by enrich, read by ``/v1``)."""

    __tablename__ = "cascades"
    __table_args__ = (
        Index(None, "last_event_at", "id"),
        Index(None, "events_1h", "id"),
        Index("ix_cascades_enrich_dirty", "id", postgresql_where=sql_text("enrich_dirty")),
        Index(None, "claim_id"),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    root_uri: Mapped[str] = mapped_column(String(URI_KEY_LENGTH), unique=True)
    claim_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("claims.id", ondelete="SET NULL")
    )
    tracking_ends_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    first_event_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    last_event_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    event_count: Mapped[int] = _counter()
    unique_accounts: Mapped[int] = _counter()
    reply_count: Mapped[int] = _counter()
    quote_count: Mapped[int] = _counter()
    repost_count: Mapped[int] = _counter()
    max_depth: Mapped[int] = _counter()
    orphan_count: Mapped[int] = _counter()
    disconnected_count: Mapped[int] = _counter()
    deleted_count: Mapped[int] = _counter()
    order_violation_count: Mapped[int] = _counter()
    events_1h: Mapped[int] = _counter()
    overflow_count: Mapped[int] = _counter()
    # Stream-time high-water mark (microseconds) of the overflow events already counted in
    # overflow_count. Written only by the collector, so a replay, a rewind or a kill-and-resume
    # cannot inflate the tally (plan 03-05); enrich never writes it.
    overflow_through_us: Mapped[int | None] = mapped_column(BigInteger)
    root_deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    enrich_dirty: Mapped[bool] = mapped_column(Boolean, server_default=sql_text("true"))
    rolled_up_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    rollup_version: Mapped[int] = _counter()


class Event(Base):
    """One observed record of a cascade: a root, a reply, a quote or a repost (D-12).

    The CHECK constraints are the edge, orphan, tombstone and minimisation rules; their names
    are the suffixes the ``ck`` convention expands (``ck_events_<name>``).
    """

    __tablename__ = "events"
    __table_args__ = (
        CheckConstraint(_in("edge_kind", EDGE_KINDS), name="edge_kind"),
        # D-12: a root, and only a root, has no parent.
        CheckConstraint("(edge_kind = 'root') = (parent_uri IS NULL)", name="root_iff_no_parent"),
        # D-12: a repost is an inferred fan-out edge; replies and quotes are observed edges.
        CheckConstraint("inferred = (edge_kind = 'repost')", name="inferred_iff_repost"),
        CheckConstraint(_in("parent_state", PARENT_STATES), name="parent_state"),
        # D-14: parent_state none means root and nothing else.
        CheckConstraint("(parent_state = 'none') = (edge_kind = 'root')", name="none_iff_root"),
        # D-18: post text only on a root, and a purged text is NULL.
        CheckConstraint("text IS NULL OR edge_kind = 'root'", name="text_only_on_root"),
        CheckConstraint("text_purged_at IS NULL OR text IS NULL", name="purged_text_is_null"),
        # D-12: a repost has no depth and contributes to no chain.
        CheckConstraint("edge_kind <> 'repost' OR depth IS NULL", name="repost_has_no_depth"),
        CheckConstraint("parent_event_id IS NULL OR parent_event_id <> id", name="no_self_parent"),
        # D-16: a tombstone keeps the skeleton and holds no account, time, text, claim or lang.
        CheckConstraint(
            "deleted_at IS NULL OR (account_id IS NULL AND occurred_at IS NULL"
            " AND text IS NULL AND claim_id IS NULL AND lang IS NULL)",
            name="tombstone_is_minimal",
        ),
        Index(None, "cascade_id", "observed_at", "uri"),
        Index(
            "ix_events_orphans",
            "cascade_id",
            postgresql_where=sql_text("parent_state = 'orphan'"),
        ),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    uri: Mapped[str] = mapped_column(String(URI_KEY_LENGTH), unique=True)
    edge_kind: Mapped[str] = mapped_column(String(8))
    inferred: Mapped[bool] = mapped_column(Boolean)
    parent_uri: Mapped[str | None] = mapped_column(String(URI_KEY_LENGTH))
    reply_root_uri: Mapped[str | None] = mapped_column(String(URI_KEY_LENGTH))
    # Secondary relations, never drawn as an edge (D-12): the quote target of a reply-quote,
    # and a repost's ``via`` reference (ratified schema_via_uri: true, RESEARCH F-07).
    quoted_uri: Mapped[str | None] = mapped_column(String(URI_KEY_LENGTH))
    via_uri: Mapped[str | None] = mapped_column(String(URI_KEY_LENGTH))
    parent_event_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("events.id", ondelete="SET NULL")
    )
    parent_state: Mapped[str] = mapped_column(String(8), server_default=sql_text("'orphan'"))
    cascade_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("cascades.id", ondelete="CASCADE")
    )
    depth: Mapped[int | None] = mapped_column(Integer)
    account_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("accounts.id", ondelete="SET NULL")
    )
    observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    occurred_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    text: Mapped[str | None] = mapped_column(Text)
    text_purged_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    claim_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("claims.id", ondelete="SET NULL")
    )
    lang: Mapped[str | None] = mapped_column(String(8))
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class IngestCheckpoint(Base):
    """The collector's resume cursor per source (moves only forward)."""

    __tablename__ = "ingest_checkpoints"

    source: Mapped[str] = mapped_column(String(64), primary_key=True)
    dialect: Mapped[str] = mapped_column(String(16))
    host: Mapped[str] = mapped_column(String(253))
    cursor_time_us: Mapped[int] = mapped_column(BigInteger)
    cursor_seq: Mapped[int | None] = mapped_column(BigInteger)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=_now())


class IngestRun(Base):
    """One collector run: mode, outcome, gap span and counts (no personal data)."""

    __tablename__ = "ingest_runs"
    __table_args__ = (CheckConstraint(_in("mode", RUN_MODES), name="mode"),)

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    source: Mapped[str] = mapped_column(String(64))
    dialect: Mapped[str | None] = mapped_column(String(16))
    host: Mapped[str | None] = mapped_column(String(253))
    mode: Mapped[str] = mapped_column(String(8))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    status: Mapped[str] = mapped_column(String(24))
    resume_from_time_us: Mapped[int | None] = mapped_column(BigInteger)
    resume_gap: Mapped[bool] = mapped_column(Boolean, server_default=sql_text("false"))
    # Several gaps in one run are merged into one conservative span.
    gap_from_us: Mapped[int | None] = mapped_column(BigInteger)
    gap_to_us: Mapped[int | None] = mapped_column(BigInteger)
    gap_count: Mapped[int] = _counter()
    last_time_us: Mapped[int | None] = mapped_column(BigInteger)
    counters: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=sql_text("'{}'::jsonb"))
    error_class: Mapped[str | None] = mapped_column(String(64))


class NewsFetch(Base):
    """The news quota ledger (D-26): one row per provider call, written before the call."""

    __tablename__ = "news_fetches"
    __table_args__ = (Index(None, "called_at"),)

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    query_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("news_queries.id", ondelete="CASCADE")
    )
    called_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    outcome: Mapped[str] = mapped_column(String(24), server_default=sql_text("'pending'"))
