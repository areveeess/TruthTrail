"""``python -m truthtrail.db {migrate,check,heads}``: the packaged migration command (D-19).

It needs no ini file, so it works inside the image, and it reads only ``DATABASE_URL``
(``get_database_settings``), never the API's ``Settings`` or any other secret.

- ``migrate``: ``alembic upgrade head`` through a ``jobs`` engine (30 s statement timeout).
- ``check``: ``alembic check``; drift between the models and the migrations is exit 1.
- ``heads``: print the packaged head revision (no database needed).

Exit codes: 0 ok, 1 drift detected, 3 configuration error (the message names the variable,
never the value), 5 database failure (the message is the exception class name only). No
output ever contains the URL or any part of it (RESEARCH F-14, pitfall 16).
"""

import argparse
import sys
from collections.abc import Sequence

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from truthtrail.core.config import ConfigurationError, get_database_settings
from truthtrail.db import migration_config, packaged_head
from truthtrail.db.engine import create_db_engine

EXIT_OK = 0
EXIT_DRIFT = 1
EXIT_CONFIG = 3
EXIT_DATABASE = 5


def _run(action: str) -> None:
    settings = get_database_settings()
    engine = create_db_engine(settings.database_url, role="jobs")
    try:
        with engine.begin() as connection:
            cfg = migration_config(connection)
            if action == "migrate":
                command.upgrade(cfg, "head")
            else:
                command.check(cfg)
    finally:
        engine.dispose()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m truthtrail.db", description="Apply or check the packaged migrations."
    )
    parser.add_argument("action", choices=("migrate", "check", "heads"))
    args = parser.parse_args(argv)
    if args.action == "heads":
        print(packaged_head())
        return EXIT_OK
    try:
        _run(args.action)
    except ConfigurationError as exc:
        print(f"configuration error: {exc}", file=sys.stderr)
        return EXIT_CONFIG
    except AutogenerateDiffsDetected:
        print("drift: the models and the migrations disagree", file=sys.stderr)
        return EXIT_DRIFT
    except Exception as exc:  # the text can carry the host; only the class name is printed
        print(f"database failure: {type(exc).__name__}", file=sys.stderr)
        return EXIT_DATABASE
    print(f"{args.action}: ok (head {packaged_head()})")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
