"""The packaged Alembic migrations on a real PostgreSQL (D-19, D-20, ROADMAP SC2).

``alembic upgrade head`` on an empty database creates the eight application tables with the
DATA-02 columns; ``alembic check`` proves the declarative models and the baseline revision agree;
``downgrade base`` leaves only ``alembic_version`` and a second ``upgrade head`` is clean again.
Both forms are exercised: the programmatic commands with a shared connection (what pytest and
``python -m truthtrail.db`` use) and the real command line from the repository root (what CI runs
against the service container). The database URL never reaches ``Config.set_main_option`` and no
failure message ever contains it (RESEARCH F-14).
"""

