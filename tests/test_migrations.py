# --- the command line (alembic and python -m truthtrail.db) ----------------------------------
def _cli(
    args: list[str], subprocess_env: dict[str, str], database_url: str | None
) -> subprocess.CompletedProcess[str]:
    env = dict(subprocess_env)
    if database_url is not None:
        env["DATABASE_URL"] = database_url
    return subprocess.run(
        [sys.executable, *args],
        cwd=ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )


@pytest.mark.requires_db
def test_alembic_command_line_upgrade_downgrade_and_check(
    empty_database: Any, subprocess_env: dict[str, str]
) -> None:
    url = empty_database()
    alembic = ["-m", "alembic", "-c", "alembic.ini"]
    for step in (["upgrade", "head"], ["downgrade", "base"], ["upgrade", "head"], ["check"]):
        result = _cli([*alembic, *step], subprocess_env, url)
        assert result.returncode == 0, (step, result.stderr[-2000:])
    assert _tables(url) == APPLICATION_TABLES | {"alembic_version"}
    assert _db_revision(url) == [packaged_head()]


@pytest.mark.requires_db
def test_alembic_command_line_check_fails_on_drift(
    fresh_url: str, subprocess_env: dict[str, str]
) -> None:
    engine = _engine(fresh_url)
    try:
        with engine.begin() as connection:
            connection.execute(text("ALTER TABLE claims ADD COLUMN drift_probe integer"))
    finally:
        engine.dispose()
    result = _cli(["-m", "alembic", "-c", "alembic.ini", "check"], subprocess_env, fresh_url)
    assert result.returncode != 0


@pytest.mark.requires_db
def test_packaged_command_migrates_and_checks_without_an_ini(
    empty_database: Any, subprocess_env: dict[str, str], tmp_path: Path
) -> None:
    url = empty_database()
    env = dict(subprocess_env)
    env["DATABASE_URL"] = url
    for action in ("migrate", "check"):
        # Run from an empty directory: no alembic.ini is reachable.
        result = subprocess.run(
            [sys.executable, "-m", "truthtrail.db", action],
            cwd=tmp_path,
            env=env,
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
        assert result.returncode == 0, result.stderr[-2000:]
        assert f"{action}: ok (head {packaged_head()})" in result.stdout
    assert _db_revision(url) == [packaged_head()]


def test_packaged_command_never_prints_the_url_or_the_password(
    subprocess_env: dict[str, str],
) -> None:
    url = f"postgresql://tt_user:p%25w{MARKER}@127.0.0.1:1/truthtrail_marker_db"
    for args in (["-m", "truthtrail.db", "migrate"], ["-m", "truthtrail.db", "check"]):
        result = _cli(args, subprocess_env, url)
        assert result.returncode == 5
        output = result.stdout + result.stderr
        assert "database failure: OperationalError" in output
        for fragment in (MARKER, "tt_user", "truthtrail_marker_db", "127.0.0.1", "postgresql"):
            assert fragment not in output
    # The alembic command line (env.py reads the variable) never echoes the password either.
    result = _cli(["-m", "alembic", "-c", "alembic.ini", "upgrade", "head"], subprocess_env, url)
    assert result.returncode != 0
    assert MARKER not in result.stdout + result.stderr


def test_packaged_command_without_database_url_exits_3(subprocess_env: dict[str, str]) -> None:
    result = _cli(["-m", "truthtrail.db", "migrate"], subprocess_env, None)
